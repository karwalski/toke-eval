#!/usr/bin/env python3
"""133.4: verify + measure the 60 KERN-benchmarked Gate-1 solutions (task-a-0001..0060).

For each id, on the committed v0.4 text in benchmark/solutions/:
  1. tkc --check            (compile gate)
  2. tkc --min              (canonical single-line form; the measured text)
  3. cl100k / o200k tokens of the --min text (tiktoken, same call as
     toke/docs/about/reviews/kern-2026-08.repro.py: encode(text.strip(), disallowed_special=()))
  4. compile + run every hidden test case through benchmark/run_benchmark.py's
     toke loader (binary <json-input> -> JSON stdout, deep-equal to expected)

Usage:
    TKC=~/tk/toke/tkc python3 scripts/gate1_60_v04.py \
        --tests-dir <dir with task-a-0001..0060.yaml> \
        [--solutions-dir benchmark/solutions] [--md docs/gate1-60-v04.md] [--json out.json]

tiktoken is optional; without it the token columns are left blank.
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tempfile
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(ROOT / "benchmark"))
import run_benchmark as rb  # noqa: E402

IDS = [f"task-a-{i:04d}" for i in range(1, 61)]

# KERN's published cl100k totals for the same 60 programs (kern-2026-08.md §6.1).
KERN_PUBLISHED = {"Kern Compact": 3012, "Python (JSON-CLI)": 3565, "toke legacy (as KERN measured)": 6347}


def run(cmd: list[str], timeout: int = 120) -> tuple[int, str, str]:
    p = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)
    return p.returncode, p.stdout, p.stderr


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--solutions-dir", type=Path, default=ROOT / "benchmark" / "solutions")
    ap.add_argument("--tests-dir", type=Path, required=True)
    ap.add_argument("--md", type=Path, default=None)
    ap.add_argument("--json", type=Path, default=None)
    ap.add_argument("--timeout", type=int, default=10)
    a = ap.parse_args()

    try:
        import tiktoken
        enc = {n: tiktoken.get_encoding(n) for n in ("cl100k_base", "o200k_base")}
    except Exception:  # pragma: no cover - optional
        enc = {}
    tkc = rb._find_tkc()
    rb._SUBPROCESS_TIMEOUT = a.timeout
    tmp = Path(tempfile.mkdtemp(prefix="gate1-60-"))
    rows = []
    for tid in IDS:
        src = a.solutions_dir / f"{tid}.toke"
        r: dict = {"task_id": tid, "bytes": src.stat().st_size}
        rc, _, _ = run([tkc, "--check", str(src)])
        r["check_ok"] = rc == 0
        rc, mn, _ = run([tkc, "--min", str(src)])
        text = mn.strip() if rc == 0 and mn.strip() else src.read_text().strip()
        r["min_ok"] = rc == 0
        r["min_bytes"] = len(text.encode())
        for n, e in enc.items():
            r[n.replace("_base", "")] = len(e.encode(text, disallowed_special=()))
        binary = tmp / tid
        ok, err = rb._compile_toke(src, binary, tkc)
        r["compile_ok"] = ok
        task = yaml.safe_load(open(a.tests_dir / f"{tid}.yaml"))
        cases = task["test_inputs"]
        r["description"] = task["description"]
        r["tests_total"] = len(cases)
        if ok:
            fn = rb._make_subprocess_runner(binary)
            res = rb.score_task(tid, fn, cases, a.timeout)
            r["tests_pass"] = res.pass_count
            r["fail_examples"] = [
                {"input": c.input, "expected": c.expected, "actual": c.actual, "error": c.error}
                for c in res.cases if not c.passed][:3]
        else:
            r["tests_pass"] = 0
            r["fail_examples"] = [{"error": err[:200]}]
        rows.append(r)
        print(tid, "check", r["check_ok"], "tests", f"{r['tests_pass']}/{r['tests_total']}",
              "cl100k", r.get("cl100k", "-"), "bytes", r["min_bytes"], flush=True)

    tot = {
        "check_ok": sum(r["check_ok"] for r in rows),
        "compile_ok": sum(r["compile_ok"] for r in rows),
        "tests_all_pass": sum(r["tests_pass"] == r["tests_total"] for r in rows),
        "min_bytes": sum(r["min_bytes"] for r in rows),
    }
    for n in ("cl100k", "o200k"):
        if n in rows[0]:
            tot[n] = sum(r[n] for r in rows)
    summary = {"tkc_version": run([tkc, "--version"])[1].strip(),
               "solutions_commit": run(["git", "-C", str(ROOT), "rev-parse", "HEAD"])[1].strip(),
               "pairs": len(rows), "totals": tot, "kern_published_cl100k": KERN_PUBLISHED, "per_task": rows}
    if a.json:
        a.json.write_text(json.dumps(summary, indent=1))
    if a.md:
        write_md(a.md, render_md(summary))
    print(json.dumps({k: v for k, v in summary.items() if k != "per_task"}, indent=1))
    return 0 if tot["tests_all_pass"] == len(rows) else 1


BEGIN, END = "<!-- gate1-60:begin (generated by scripts/gate1_60_v04.py) -->", "<!-- gate1-60:end -->"


def write_md(path: Path, body: str) -> None:
    """Replace the generated block between the markers; keep hand-written prose around it."""
    if path.exists() and BEGIN in path.read_text() and END in path.read_text():
        old = path.read_text()
        head, rest = old.split(BEGIN, 1)
        _, tail = rest.split(END, 1)
        path.write_text(f"{head}{BEGIN}\n{body}{END}{tail}")
    else:
        path.write_text(f"# Gate-1 60 — v0.4 solutions (133.4)\n\n{BEGIN}\n{body}{END}\n")


def render_md(s: dict) -> str:
    rows = s["per_task"]
    tot = s["totals"]
    has_tok = "cl100k" in tot
    out = [f"Measured with tkc {s['tkc_version']} on toke-eval `{s['solutions_commit'][:8]}` "
           f"(`TKC=~/tk/toke/tkc python3 scripts/gate1_60_v04.py --tests-dir <hidden_tests> --md docs/gate1-60-v04.md`).",
           "", "## Totals (60 programs)", "",
           "| Representation | cl100k | o200k | bytes | compile | tests |", "|---|---:|---:|---:|---:|---:|"]
    if has_tok:
        out.append(f"| **toke v0.4 `--min` (this set)** | **{tot['cl100k']:,}** | {tot['o200k']:,} | {tot['min_bytes']:,} | "
                   f"{tot['check_ok']}/60 | {tot['tests_all_pass']}/60 |")
    else:
        out.append(f"| **toke v0.4 `--min` (this set)** | n/a | n/a | {tot['min_bytes']:,} | {tot['check_ok']}/60 | {tot['tests_all_pass']}/60 |")
    for k, v in s["kern_published_cl100k"].items():
        out.append(f"| {k} (KERN published) | {v:,} | | | | |")
    out += ["", "## Per task", "",
            "| id | description | `--check` | tests | cl100k | o200k | bytes (`--min`) |", "|---|---|:-:|---:|---:|---:|---:|"]
    for r in rows:
        out.append(f"| {r['task_id']} | {r['description'][:48]} | {'ok' if r['check_ok'] else 'FAIL'} | "
                   f"{r['tests_pass']}/{r['tests_total']} | {r.get('cl100k', '')} | {r.get('o200k', '')} | {r['min_bytes']} |")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    sys.exit(main())
