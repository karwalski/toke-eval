#!/usr/bin/env python3
"""133.4 Part B: reproduce the check / harness numbers for benchmark/solutions.

Two gates over every ``task-a-NNNN.toke`` in ``--solutions-dir``:

  1. ``tkc --check``      -> clean, or the first error code (the "class")
  2. the existing harness  (``benchmark/run_benchmark.py --language toke``)
     -> per-id pass/fail, taken ONLY from the harness's JSON report
     (``pass_count`` / ``total_count`` per task id).

Hidden-tests isolation (workspace AGENTS.md section 5): this script never opens,
lists or reads anything under a ``hidden_tests/`` directory.  It passes the
directory to the harness as ``--tasks-dir`` and discards the harness's stdout and
stderr (which may echo test inputs on failure); it reads back only the JSON
report the harness writes, which carries counts and nothing else
(``report_to_dict`` drops per-case detail).

Several ``--tasks-dir`` may be given; for an id evaluated by more than one, the
first directory wins.  Ids no directory evaluates are reported as "no tests".

Usage:
    TKC=~/tk/toke/tkc python3 scripts/solutions_v04.py \\
        --tasks-dir benchmark/hidden_tests \\
        --tasks-dir <dir holding the task-a-0001..0500 YAMLs> \\
        [--solutions-dir benchmark/solutions] [--json out.json] [--md docs/solutions-v04.md]

``--no-harness`` runs gate 1 only.
"""
from __future__ import annotations

import argparse
import collections
import concurrent.futures as cf
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
HARNESS = ROOT / "benchmark" / "run_benchmark.py"
BEGIN = "<!-- solutions-v04:begin (generated by scripts/solutions_v04.py) -->"
END = "<!-- solutions-v04:end -->"


def find_tkc() -> str:
    sys.path.insert(0, str(ROOT / "benchmark"))
    import run_benchmark as rb  # noqa: E402
    return rb._find_tkc()


def check_one(tkc: str, src: Path) -> str:
    p = subprocess.run([tkc, "--check", str(src)], capture_output=True, text=True,
                       timeout=120)
    if p.returncode == 0:
        return "ok"
    for line in (p.stdout + "\n" + p.stderr).splitlines():
        try:
            d = json.loads(line)
        except ValueError:
            continue
        if d.get("severity") == "error":
            return d.get("error_code", "?")
    return f"rc{p.returncode}"


def harness_shard(tkc: str, files: list[Path], tasks_dir: Path, timeout: int) -> dict:
    """Run the existing harness over one shard; return {id: (pass, total)}."""
    with tempfile.TemporaryDirectory(prefix="sol-v04-") as td:
        sd = Path(td) / "solutions"
        sd.mkdir()
        for f in files:
            shutil.copy2(f, sd / f.name)
        out = Path(td) / "report.json"
        env = dict(os.environ, TKC=tkc)
        p = subprocess.run(
            [sys.executable, str(HARNESS), "--language", "toke",
             "--solutions-dir", str(sd), "--tasks-dir", str(tasks_dir),
             "--timeout", str(timeout), "--output", str(out)],
            env=env, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
        )
        if not out.exists():  # zero overlap with this tasks dir, or harness error
            print(f"note: harness wrote no report for a {len(files)}-file shard "
                  f"against {tasks_dir.name} (rc {p.returncode}); its output is "
                  f"deliberately not shown", file=sys.stderr)
            return {}
        rep = json.loads(out.read_text())
        return {t["task_id"]: (t["pass_count"], t["total_count"]) for t in rep["tasks"]}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--solutions-dir", type=Path, default=ROOT / "benchmark" / "solutions")
    ap.add_argument("--tasks-dir", type=Path, action="append", default=[])
    ap.add_argument("--no-harness", action="store_true")
    ap.add_argument("--jobs", type=int, default=4)
    ap.add_argument("--timeout", type=int, default=10)
    ap.add_argument("--json", type=Path)
    ap.add_argument("--md", type=Path)
    a = ap.parse_args()

    tkc = os.environ.get("TKC") or find_tkc()
    ver = subprocess.run([tkc, "--version"], capture_output=True, text=True).stdout.strip()
    files = sorted(a.solutions_dir.glob("task-a-*.toke"))
    ids = [f.stem for f in files]

    with cf.ThreadPoolExecutor(a.jobs) as ex:
        check = dict(zip(ids, ex.map(lambda f: check_one(tkc, f), files)))

    harness: dict[str, tuple[int, int]] = {}
    if not a.no_harness:
        for td in a.tasks_dir:
            todo = [f for f in files if f.stem not in harness]
            shards = [todo[i::a.jobs] for i in range(a.jobs)]
            with cf.ThreadPoolExecutor(a.jobs) as ex:
                for res in ex.map(lambda s: harness_shard(tkc, s, td.resolve(), a.timeout), shards):
                    for k, v in res.items():
                        harness.setdefault(k, v)

    rows = []
    for tid in ids:
        h = harness.get(tid)
        rows.append({
            "task_id": tid,
            "check": check[tid],
            "harness": None if h is None else ("pass" if h[0] == h[1] else "fail"),
            "cases": None if h is None else f"{h[0]}/{h[1]}",
        })

    n = len(rows)
    n_clean = sum(r["check"] == "ok" for r in rows)
    classes = collections.Counter(r["check"] for r in rows if r["check"] != "ok")
    tested = [r for r in rows if r["harness"] is not None]
    n_pass = sum(r["harness"] == "pass" for r in tested)
    untested = [r["task_id"] for r in rows if r["harness"] is None]
    summary = {
        "tkc": ver, "solutions": n, "check_clean": n_clean,
        "check_classes": dict(classes.most_common()),
        "harness_evaluated": len(tested), "harness_pass": n_pass,
        "no_tests": untested if not a.no_harness else None,
        "residue": {
            "check": {c: [r["task_id"] for r in rows if r["check"] == c] for c in classes},
            "harness_fail_check_clean": [r["task_id"] for r in tested
                                         if r["harness"] == "fail" and r["check"] == "ok"],
        },
    }
    print(f"tkc: {ver}")
    print(f"check-clean: {n_clean}/{n}   classes: {dict(classes.most_common())}")
    if not a.no_harness:
        print(f"harness-pass: {n_pass}/{len(tested)} evaluated ({len(untested)} ids with no tests)")
        print(f"harness fail (check-clean): {summary['residue']['harness_fail_check_clean']}")
    if a.json:
        a.json.write_text(json.dumps({"summary": summary, "rows": rows}, indent=1) + "\n")
    if a.md:
        block = [BEGIN, "",
                 f"Measured with `{ver}` by `scripts/solutions_v04.py`.", "",
                 "| gate | result |", "|---|---:|",
                 f"| `tkc --check` clean | {n_clean}/{n} |"]
        if not a.no_harness:
            block.append(f"| harness pass (ids with tests) | {n_pass}/{len(tested)} |")
            block.append(f"| ids with no test file | {len(untested)} |")
        block += ["", "| check class | count | ids |", "|---|---:|---|"]
        for c, k in classes.most_common():
            block.append(f"| {c} | {k} | {', '.join(t[7:] for t in summary['residue']['check'][c])} |")
        if not a.no_harness:
            hf = summary["residue"]["harness_fail_check_clean"]
            block.append(f"| check-clean, harness fail | {len(hf)} | {', '.join(t[7:] for t in hf)} |")
        block += ["", END]
        text = a.md.read_text() if a.md.exists() else ""
        if BEGIN in text and END in text:
            pre, rest = text.split(BEGIN, 1)
            text = pre + "\n".join(block) + rest.split(END, 1)[1]
        else:
            text = text + "\n" + "\n".join(block) + "\n"
        a.md.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
